#!/usr/bin/env node
// Pull ESPN scoreboards for camp-open week and write a committed snapshot.
// Schedule only — no scores, no invented matchups. Safe to run in September.

import { writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath, pathToFileURL } from "url";
import { fetchESPNCached, parseGames } from "./lib/espn-cache.mjs";
import { canonicalNbaAbbrev, TEAM_ABBR_SET } from "./lib/content-quality-constants.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "client/src/lib/campScheduleData.ts");

/** Keep in sync with client/src/lib/enhancedDesk.ts CAMP_OPEN_ISO. */
export const CAMP_OPEN_ISO = "2026-10-03";
export const CAMP_WINDOW_DAYS = 8;

export function dateWindow(startIso = CAMP_OPEN_ISO, days = CAMP_WINDOW_DAYS) {
  const start = new Date(`${startIso}T12:00:00Z`);
  const out = [];
  for (let i = 0; i < days; i++) {
    const d = new Date(start.getTime());
    d.setUTCDate(d.getUTCDate() + i);
    out.push(d.toISOString().slice(0, 10).replace(/-/g, ""));
  }
  return out;
}

export function isoFromEspnDate(yyyymmdd) {
  return `${yyyymmdd.slice(0, 4)}-${yyyymmdd.slice(4, 6)}-${yyyymmdd.slice(6, 8)}`;
}

export function normalizeCampGame(game, dateIso) {
  const away = canonicalNbaAbbrev(String(game.awayTeam ?? "").toUpperCase());
  const home = canonicalNbaAbbrev(String(game.homeTeam ?? "").toUpperCase());
  return {
    dateIso,
    when: game.time || dateIso,
    away,
    home,
    tv: game.tv && game.tv !== "Local" ? String(game.tv) : "",
    venue: game.venue ? String(game.venue) : "",
  };
}

export function isCanonicalPair(game) {
  return TEAM_ABBR_SET.has(game.away) && TEAM_ABBR_SET.has(game.home);
}

function renderFile(games, windowStart, windowEnd) {
  const fetchedAt = new Date().toISOString();
  const rows = games
    .map(
      (g) =>
        `  {dateIso:${JSON.stringify(g.dateIso)},when:${JSON.stringify(g.when)},away:${JSON.stringify(g.away)},home:${JSON.stringify(g.home)},tv:${JSON.stringify(g.tv)},venue:${JSON.stringify(g.venue)}},`,
    )
    .join("\n");

  return `// Auto-generated by scripts/fetch-camp-schedule.mjs — ESPN camp-week slate only.
// Not tonight's scoreboard. Do not treat these as live scores.

export interface CampScheduleGame {
  dateIso: string;
  when: string;
  away: string;
  home: string;
  tv: string;
  venue: string;
}

export const campScheduleMeta = {
  fetchedAt: ${JSON.stringify(fetchedAt)},
  source: "ESPN scoreboard",
  windowStart: ${JSON.stringify(windowStart)},
  windowEnd: ${JSON.stringify(windowEnd)},
  label: "ESPN camp-week slate — not tonight",
};

export const campScheduleGames: CampScheduleGame[] = [
${rows}
];
`;
}

export async function fetchCampScheduleGames(dates = dateWindow()) {
  const games = [];
  for (const ymd of dates) {
    const data = await fetchESPNCached(ymd);
    const parsed = parseGames(data);
    const iso = isoFromEspnDate(ymd);
    for (const game of parsed) {
      const row = normalizeCampGame(game, iso);
      if (isCanonicalPair(row)) games.push(row);
    }
  }
  return games;
}

async function main() {
  const dates = dateWindow();
  const windowStart = isoFromEspnDate(dates[0]);
  const windowEnd = isoFromEspnDate(dates[dates.length - 1]);
  console.log(`🏀 ESPN camp-week schedule ${windowStart} → ${windowEnd}`);
  const games = await fetchCampScheduleGames(dates);
  writeFileSync(OUT, renderFile(games, windowStart, windowEnd), "utf8");
  console.log(`✓ Wrote ${games.length} ESPN camp-week games to client/src/lib/campScheduleData.ts`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(`✗ fetch-camp-schedule: ${err.message}`);
    process.exit(1);
  });
}
